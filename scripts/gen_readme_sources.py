"""Regenerate the citation section of README.md from data/planets/*.json.

Run: python scripts/gen_readme_sources.py      (rewrites README between the SOURCES markers)
     python scripts/gen_readme_sources.py --check   (exit 1 if README is out of date)
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from planet_helper.data import load_dataset  # noqa: E402

START, END = "<!-- SOURCES:START (generated by scripts/gen_readme_sources.py) -->", "<!-- SOURCES:END -->"


def render() -> str:
    ds = load_dataset(ROOT / "data" / "planets")
    if ds.errors:
        raise SystemExit("data errors:\n" + "\n".join(ds.errors))
    out = [START, ""]
    for pid in sorted(ds.planets, key=lambda p: (p != "aris", ds.planets[p]["planet"]["name"].lower())):
        doc = ds.planets[pid]
        p = doc["planet"]
        out.append(f"### {p['name']} ({p['status']}, reviewed {p['lastReviewed']})")
        out.append("")
        used_by: dict[str, list[str]] = {}
        for a in doc["activities"]:
            for sid in a["sourceIds"]:
                used_by.setdefault(sid, []).append(a["title"])
        for sid in p["sourceIds"]:
            used_by.setdefault(sid, []).insert(0, "destination overview")
        for s in doc["sources"]:
            topics = used_by.get(s["id"], [])
            topic_txt = "; ".join(dict.fromkeys(topics)) if topics else "background"
            pub = s["published"] or "undated"
            out.append(f"- [{s['title']}]({s['url']}) — {s['publisher']} ({s['kind']}), published {pub}, "
                       f"checked {s['accessed']}. Supports: {s['supports']} Used for: {topic_txt}.")
        out.append("")
    out.append(END)
    return "\n".join(out)


def main() -> int:
    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise SystemExit("README.md lacks the SOURCES markers")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    new = head + render() + tail
    if "--check" in sys.argv:
        if new != text:
            print("README.md sources are out of date; run python scripts/gen_readme_sources.py")
            return 1
        print("README.md sources up to date")
        return 0
    readme.write_text(new, encoding="utf-8", newline="\n")
    print("README.md sources regenerated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
